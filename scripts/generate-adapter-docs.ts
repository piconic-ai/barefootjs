#!/usr/bin/env bun
//
// Regenerate the adapter tables in README.md and
// docs/core/core-concepts/backend-freedom.md from the single source of
// truth: ADAPTER_ENTRIES (packages/compat/src/adapter-doc-catalog.ts),
// which is itself floor-checked against the compiled adapter registry
// (packages/compat/src/adapter-registry.ts) — see
// adapter-doc-catalog.test.ts.
//
// Usage: bun run scripts/generate-adapter-docs.ts [--check]
//
//   (no flags)  Rewrite the generated regions in place.
//   --check     Exit 1 if regenerating would change either file, without
//               writing — used by .github/workflows/update-adapter-docs.yml.
//
// Both target files carry a matched pair of HTML-comment markers
// (`ADAPTER-TABLE:START` / `ADAPTER-TABLE:END`); only the text between
// them is replaced, so hand-written prose around the table survives.

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { assertAdapterDocCatalogComplete, ADAPTER_ENTRIES, type AdapterEntry } from '../packages/compat/src/adapter-doc-catalog'

const ROOT = fileURLToPath(new URL('..', import.meta.url))

const MARKER_START = '<!-- ADAPTER-TABLE:START (auto-generated by scripts/generate-adapter-docs.ts — do not edit by hand) -->'
const MARKER_END = '<!-- ADAPTER-TABLE:END -->'

interface Target {
  /** Path relative to repo root. */
  path: string
  /** Prefix to join with each family's `docPage` to build the link href. */
  docPathPrefix: string
}

const TARGETS: Target[] = [
  { path: 'README.md', docPathPrefix: 'docs/core/' },
  { path: 'docs/core/core-concepts/backend-freedom.md', docPathPrefix: '../' },
]

function renderTable(docPathPrefix: string): string {
  const header = '| Language | Backend | Package |'
  const separator = '|----------|---------|---------|'
  const rows = ADAPTER_ENTRIES.map((entry: AdapterEntry) => {
    const link = `[${entry.backend}](${docPathPrefix}${entry.docPage})`
    return `| ${entry.language} | ${link} | \`${entry.pkg}\` |`
  })
  return [header, separator, ...rows].join('\n')
}

function withRegeneratedTable(source: string, table: string, filePath: string): string {
  const startIdx = source.indexOf(MARKER_START)
  const endIdx = source.indexOf(MARKER_END)
  if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) {
    throw new Error(`${filePath}: missing or misordered ADAPTER-TABLE markers — expected both\n  ${MARKER_START}\nand\n  ${MARKER_END}`)
  }
  const before = source.slice(0, startIdx + MARKER_START.length)
  const after = source.slice(endIdx)
  return `${before}\n${table}\n${after}`
}

function main(): void {
  assertAdapterDocCatalogComplete()

  const checkOnly = process.argv.includes('--check')
  let drifted = false

  for (const target of TARGETS) {
    const filePath = join(ROOT, target.path)
    const original = readFileSync(filePath, 'utf8')
    const table = renderTable(target.docPathPrefix)
    const updated = withRegeneratedTable(original, table, target.path)

    if (updated === original) {
      console.log(`${target.path}: up to date`)
      continue
    }

    drifted = true
    if (checkOnly) {
      console.log(`${target.path}: OUT OF DATE`)
      continue
    }

    writeFileSync(filePath, updated)
    console.log(`${target.path}: regenerated`)
  }

  if (checkOnly && drifted) {
    console.error(
      "\nAdapter tables are out of date. Run 'bun run docs:adapters' locally and commit the result.",
    )
    process.exit(1)
  }
}

main()
