/**
 * String-literal ternary branches whose source carries escape sequences
 * (`'a\nb'`, `'back\\slash'`, `"it's"`, `'q\'y'`) must be re-emitted as
 * valid string literals in every position the compiler prints them: the
 * IR keeps the cooked value, so printing it between bare quotes produced
 * a raw newline (an unterminated literal) or an unbalanced quote in the
 * Hono TSX and the client JS.
 *
 * Positions: attribute ternary (prop- and signal-driven), ternary inside
 * an attribute template literal, text ternary, `&&`, memo body, a child
 * prop and the child's own `function C(props)` ternary, and loop-row
 * attributes. The interactions flip the signal so the client JS update
 * path (and the loop-row / child-prop updates) re-run with the escaped
 * values.
 *
 * Snapshots in `__snapshots__/escaped-ternary-branch.{html,client.js}`
 * are regenerated by
 * `bun run packages/adapter-tests/scripts/snapshot.ts escaped-ternary-branch`.
 */

