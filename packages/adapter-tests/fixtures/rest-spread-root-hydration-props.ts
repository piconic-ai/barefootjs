/**
 * #3845: the keys of a closed-type `...rest` spread onto the root element
 * reach the client only through that spread
 * (`fixtures/components/RestSpreadRootHydrationProps.tsx`). The client reads
 * each one live as `_p.<key>` and drops the attribute when it reads nullish,
 * so the hydration payload (`bf-p`) must carry them: without them hydration
 * removes `tone` and `size` from the server-rendered button.
 *
 * The SSR HTML was already right on every adapter. `bf-p` itself is checked
 * by the hydration payload conformance suite
 * (`src/hydration-payload-conformance.ts`), since `expectedHtml` comparison
 * strips it, and in a real browser by `e2e/fixture-hydrate.playwright.ts`
 * through the interactions below: the attributes must survive hydration and
 * a click.
 *
 * Snapshots in `__snapshots__/rest-spread-root-hydration-props.{html,client.js}`
 * are regenerated by
 * `bun run packages/adapter-tests/scripts/snapshot.ts rest-spread-root-hydration-props`.
 */

import { defineSharedFixture, type SharedFixtureSpec } from './_helpers'

export const spec: SharedFixtureSpec = {
  id: 'rest-spread-root-hydration-props',
  componentName: 'RestSpreadRootHydrationProps',
  sourceRoot: 'fixture',
  description: 'closed-type rest keys spread onto the root element travel in bf-p (#3845)',
  props: { label: 'x', tone: 'info', size: 2 },
  interactions: [
    // After hydration: the spread attributes are still on the root.
    { type: 'expectAttribute', selector: 'button', attribute: 'tone', value: 'info' },
    { type: 'expectAttribute', selector: 'button', attribute: 'size', value: '2' },
    // The click proves hydration completed, and the attributes stay.
    { type: 'click', selector: 'button' },
    { type: 'expectText', selector: 'button', text: 'x!' },
    { type: 'expectAttribute', selector: 'button', attribute: 'tone', value: 'info' },
    { type: 'expectAttribute', selector: 'button', attribute: 'size', value: '2' },
  ],
}

export const fixture = defineSharedFixture(spec)
