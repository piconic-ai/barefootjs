/**
 * A destructured prop parameter the component writes in its event handlers
 * (`++start`, `start += …`, `start = start * 2`) is a local the component
 * owns: the init body declares it once from the prop and every handler reads
 * and writes that local. The client used to rewrite each reference into the
 * live prop read, write positions included (`++(_p.start ?? 0)`), which is a
 * SyntaxError that broke the whole module.
 *
 * `step` is never written, so it stays the live prop read; a handler's own
 * `for (let step …)` shadows it, and that loop's `step++` must stay the loop
 * variable's (it used to become `(_p.step ?? 1)++`).
 *
 * `.start` keeps the prop's value: nothing re-renders the markup after a
 * handler writes the local, on SSR or on the client.
 *
 * Snapshots in `__snapshots__/reassigned-prop-counter.{html,client.js}` are
 * regenerated by `bun run packages/adapter-tests/scripts/snapshot.ts
 * reassigned-prop-counter`.
 */

import { defineSharedFixture, type SharedFixtureSpec } from './_helpers'

export const spec: SharedFixtureSpec = {
  id: 'reassigned-prop-counter',
  componentName: 'ReassignedPropCounter',
  sourceRoot: 'fixture',
  description:
    'a destructured prop written by event handlers (++start, start += …, start = …) is a local the client declares once, not a live prop read',
  props: { start: 10 },
  interactions: [
    { type: 'expectText', selector: '.start', text: '10' },
    { type: 'expectText', selector: '.items', text: '' },
    { type: 'click', selector: '.add-pre' },
    { type: 'expectText', selector: '.items', text: '11' },
    // `step` (default 1) times the two laps of the shadowing loop.
    { type: 'click', selector: '.add-step' },
    { type: 'expectText', selector: '.items', text: '11,13' },
    { type: 'click', selector: '.add-double' },
    { type: 'expectText', selector: '.items', text: '11,13,26' },
    { type: 'expectText', selector: '.start', text: '10' },
  ],
}

export const fixture = defineSharedFixture(spec)
