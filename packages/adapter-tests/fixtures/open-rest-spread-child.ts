/**
 * #3714: an open-type `...rest` bag spread onto a child component
 * (`fixtures/components/OpenRestSpreadChild.tsx`). The rest object holds the
 * caller's props without the key the component destructured (`title`), so:
 *
 *   - `<Chip {...rest} />` gets no `title` (it prints `none`), where the
 *     client used to forward the caller's whole props object;
 *   - `<Chip title="x" tone="first" {...rest} />` keeps the explicit
 *     `title`, and the caller's `tone` overrides the one written before the
 *     spread;
 *   - `<Chip {...rest} size="last" />` keeps the explicit `size` written
 *     after it;
 *   - the same in a conditional branch and in loop rows.
 *
 * The interactions check the hydrated children, then a caller prop the bag
 * carries (`tone`) changing after mount: every child follows it, and `title` still does not appear. `oracle.playwright.ts` compares the
 * same fixture mounted on the client against the server render.
 *
 * Snapshots in `__snapshots__/open-rest-spread-child.{html,client.js}` are
 * regenerated by
 * `bun run packages/adapter-tests/scripts/snapshot.ts open-rest-spread-child`.
 */

