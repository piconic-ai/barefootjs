/**
 * Callback parameters named `props` in a component with destructured props.
 * The client JS renames the component's props object to `_p`; a parameter
 * spelled `props` (a reactive `.map()` row, a handler arrow, a `.filter()`
 * callback inside a handler, a nested function) shadows that name in its own
 * scope and keeps its own binding, so the outer prop reads emitted inside the
 * same scope (`_p.suffix`, `_p.step`) still reach the component's props.
 * Source lives in the fixture-only root
 * (`fixtures/components/LoopParamNamedProps.tsx`).
 *
 * Interactions: a row created client-side keeps `suffix` in its text and in
 * the forwarded child prop; the handler arrow and the filter callback read
 * `step`; the nested function reads `suffix`; a handler whose `var props`
 * sits in a nested block reads that local after the block. The rendered row
 * reads its item bare; a `props.<member>` read in a rendered row is the
 * separate template-adapter gap pinned by `loop-param-named-props-member`.
 *
 * Snapshots in `__snapshots__/loop-param-named-props.{html,client.js}` are
 * regenerated by `bun run packages/adapter-tests/scripts/snapshot.ts loop-param-named-props`.
 */

import { defineSharedFixture, type SharedFixtureSpec } from './_helpers'

export const spec: SharedFixtureSpec = {
  id: 'loop-param-named-props',
  componentName: 'LoopParamNamedProps',
  sourceRoot: 'fixture',
  description: 'Callback parameters named props keep their own binding while outer destructured-prop reads in the same scope reach the component props',
  props: { suffix: '!', step: 2 },
  interactions: [
    { type: 'expectText', selector: '.rows li:nth-child(1) .label', text: 'a!' },
    { type: 'expectText', selector: '.rows li:nth-child(2) .tag', text: 'b!' },
    // A row created client-side reads `suffix` through the outer props.
    { type: 'click', selector: '.add' },
    { type: 'expectText', selector: '.rows li:nth-child(3) .label', text: 'c!' },
    { type: 'expectText', selector: '.rows li:nth-child(3) .tag', text: 'c!' },
    // Handler arrow `(props) => … props.by * step`.
    { type: 'click', selector: '.bump' },
    { type: 'expectText', selector: '.total', text: '4' },
    // Filter callback `(props) => props !== items()[step - 1]` drops row 'b'.
    { type: 'click', selector: '.drop' },
    { type: 'expectText', selector: '.rows li:nth-child(2) .label', text: 'c!' },
    { type: 'expectHidden', selector: '.rows li:nth-child(3)' },
    // Nested `function describe(props)` reads `suffix`.
    { type: 'click', selector: '.say' },
    { type: 'expectText', selector: '.last', text: 'x!' },
    // A block-nested `var props` binds in the whole handler: 4 + 10 * step.
    { type: 'click', selector: '.hoist' },
    { type: 'expectText', selector: '.total', text: '24' },
  ],
}

export const fixture = defineSharedFixture(spec)
